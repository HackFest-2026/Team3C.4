async function seedAllGoldData() {
  const uri = process.env.MONGODB_URI || process.env.MONGO_URI || "mongodb://127.0.0.1:27017/mineguard";

  try {
    console.log(`[ACDS Gold Mines Seeder] Connecting to ${uri}...`);
    await mongoose.connect(uri);
    console.log("[ACDS Gold Mines Seeder] Connected to MongoDB.");

    // 1. Seed Equipment
    await Equipment.deleteMany({});
    await Equipment.insertMany(goldEquipment);
    console.log(`✓ Seeded ${goldEquipment.length} gold mining heavy equipment units.`);

    // 2. Seed Inventory
    await Inventory.deleteMany({});
    await Inventory.insertMany(goldInventory);
    console.log(`✓ Seeded ${goldInventory.length} gold mining warehouse inventory items.`);

    // 3. Seed Waste (strictly <= 50 tons)
    await Waste.deleteMany({});
    await Waste.insertMany(goldWaste);
    console.log(`✓ Seeded ${goldWaste.length} gold mining tailings & waste records (all <= 50 tons).`);

    // 4. Seed Compliance
    await Compliance.deleteMany({});
    await Compliance.insertMany(goldCompliance);
    console.log(`✓ Seeded ${goldCompliance.length} gold mining compliance & DGMS statutory records.`);

    await mongoose.disconnect();
    console.log("[ACDS Gold Mines Seeder] Database updated successfully!");
    process.exit(0);
  } catch (err) {
    console.error("[ACDS Gold Mines Seeder] Error seeding data:", err);
    process.exit(1);
  }
}

