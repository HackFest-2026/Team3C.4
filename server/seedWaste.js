async function seedWaste() {
  try {
    await mongoose.connect(process.env.MONGO_URI);

    console.log("MongoDB Connected");

    await Waste.deleteMany({});

    await Waste.insertMany(wasteRecords);

    console.log("20 waste/material records inserted successfully.");

    await mongoose.disconnect();

    console.log("MongoDB Disconnected");
  } catch (error) {
    console.error("Waste seed error:", error);
    process.exit(1);
  }
}

seedWaste();